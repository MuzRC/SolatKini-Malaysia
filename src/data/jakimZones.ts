export const DEFAULT_ZONE = JAKIM_ZONES[0]; // WLY01 Kuala Lumpur & Putrajaya

export function findZoneByCode(code: string): JakimZone {
  return JAKIM_ZONES.find((z) => z.code === code) || DEFAULT_ZONE;
}

export function findNearestZone(lat: number, lng: number): JakimZone {
  let minDistance = Infinity;
  let nearest = DEFAULT_ZONE;

  for (const zone of JAKIM_ZONES) {
    const dLat = (zone.lat - lat) * (Math.PI / 180);
    const dLng = (zone.lng - lng) * (Math.PI / 180);
    const a =
      Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(lat * (Math.PI / 180)) *
        Math.cos(zone.lat * (Math.PI / 180)) *
        Math.sin(dLng / 2) *
        Math.sin(dLng / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const distance = 6371 * c; // Earth radius in km

    if (distance < minDistance) {
      minDistance = distance;
      nearest = zone;
    }
  }

  return nearest;
}
